import type { ProjectType } from '../detect/project.js';

/**
 * Per-stack integration files.
 *
 * The SDK is framework-agnostic, so this is the only framework-aware part of
 * the CLI. Each adapter emits the minimum needed to get a CSS selector and a
 * `{ size, position }` layout in front of `clirevenue.render()`, and nothing
 * more. No adapter imports React into a Vue project or adds a build step to a
 * static page.
 *
 * Two invariants hold across every adapter, and they are the reason the
 * editor is not a demo:
 *
 * 1. **The layout is read at runtime from `clirevenue.config.json`,** the
 *    same file the placement editor writes. Hardcoding a size into generated
 *    code would mean dragging the box in the editor changed nothing at
 *    runtime.
 * 2. **The publisher key stays in the environment.** Only the publishable
 *    key (`pk_live_…`/`pk_test_…`) is ever referenced, and only through
 *    `import.meta.env` or `process.env`. No server-side secret is emitted,
 *    and no key is inlined into a source file where it would be bundled.
 */

export const GENERATED_HEADER = "// Generated by `clirevenue setup`. Edits are overwritten on re-run.\n";

/** Where each stack keeps the adapter, relative to the project root. */
export const ADAPTER_FILES: Record<ProjectType, { entry: string; render: string | null }> = {
  'vite-react': { entry: 'src/lib/clirevenue.js', render: 'src/components/CLIRevenueAd.jsx' },
  'vite-vue': { entry: 'src/lib/clirevenue.js', render: 'src/components/CLIRevenueAd.vue' },
  'vite-svelte': { entry: 'src/lib/clirevenue.js', render: 'src/components/CLIRevenueAd.svelte' },
  'vite-vanilla': { entry: 'src/lib/clirevenue.js', render: null },
  'static-html': { entry: 'clirevenue-ad.js', render: null },
  node: { entry: '', render: null },
  unsupported: { entry: '', render: null },
};

/** The Vite entry module, shared by every bundled stack. */
const VITE_ENTRY = `${GENERATED_HEADER}
import { init } from '@clirevenue/sdk';
import clirevenueConfig from '../../clirevenue.config.json';

// Only the publishable key is ever read here. It is designed to be visible
// to the browser; the secret key stays on the server and is never shipped.
export const clirevenue = init(import.meta.env.VITE_CLIREVENUE_PUBLISHABLE_KEY, {
  baseUrl: import.meta.env.VITE_API_BASE_URL,
});

/**
 * Render a slot using the geometry saved by \`clirevenue editor\`.
 *
 * The layout is looked up at call time, not baked in, so moving the ad in
 * the editor takes effect on the next page load without regenerating this
 * file.
 *
 * A \`placement\` is a backend placement key; a \`slot\` is one position on one
 * page. Many slots may share a placement key -- that is how a page can show
 * three ads without the backend knowing anything about it -- so the two are
 * resolved separately: the slot supplies the geometry, its integration
 * supplies the key the SDK fetches the creative for.
 */
export function renderPlacement(placementKey, selector, slotId) {
  const placement = findSlot(clirevenueConfig, placementKey, slotId);
  if (!placement) {
    console.warn(
      '[clirevenue] No saved slot for "' + placementKey + '". Run: npx clirevenue editor',
    );
    return null;
  }
  return clirevenue.render(placement.placementKey, selector, {
    size: placement.layout.size,
    position: placement.layout.position,
  });
}

/**
 * Resolve one slot out of the config.
 *
 * Accepts either the integration id or its placement key, because both are
 * natural things for a user to type, and falls back to the integration's
 * first slot so the common single-ad case needs no slot id at all. A disabled
 * slot resolves to nothing: the user turned it off, and rendering it anyway
 * would make "disable" look broken.
 */
export function findSlot(config, placementKey, slotId) {
  const integrations = config.integrations || {};
  const integration =
    integrations[placementKey] ||
    Object.values(integrations).find((entry) => entry.placementKey === placementKey);
  if (!integration) return null;

  const slots = Object.values(integration.slots || {});
  const slot = slotId ? integration.slots?.[slotId] : slots.find((entry) => entry.enabled) || slots[0];
  if (!slot || slot.enabled === false) return null;

  return { placementKey: integration.placementKey, layout: slot.layout, container: slot.container };
}
`;

/**
 * The static-HTML adapter.
 *
 * No bundler means a bare `import '@clirevenue/sdk'` cannot resolve in the
 * browser, and the config cannot be statically imported. Both differences are
 * handled explicitly — CDN ESM and a runtime `fetch` — rather than by quietly
 * telling the user to install a build step.
 */
const STATIC_ENTRY = `${GENERATED_HEADER}
// Static HTML integration: no bundler required.
// The SDK is loaded as an ES module from a CDN, and the placement config is
// fetched at runtime. Only the publishable key is used here; the secret key
// is never shipped to the browser.
const SDK_URL = 'https://esm.sh/@clirevenue/sdk@' + __SDK_VERSION__;
const CONFIG_URL = '/clirevenue.config.json';

let sdk = null;

async function loadSdk() {
  if (sdk) return sdk;
  sdk = await import(/* @vite-ignore */ SDK_URL);
  return sdk;
}

function readPublishableKey() {
  // meta keeps the key out of the bundle source; window keeps it out of the
  // repo. Neither is a server-side secret.
  const meta = document.querySelector('meta[name="clirevenue-publishable-key"]');
  if (meta?.content) return meta.content;
  try {
    return window.localStorage.getItem('clirevenue.publishableKey') || '';
  } catch {
    return '';
  }
}

function readBaseUrl() {
  const meta = document.querySelector('meta[name="clirevenue-base-url"]');
  return meta?.content || 'https://api.clirevenue.in';
}

async function loadConfig() {
  const res = await fetch(CONFIG_URL, { cache: 'no-store' });
  if (!res.ok) throw new Error('Could not load ' + CONFIG_URL + ' (HTTP ' + res.status + ')');
  return res.json();
}

/**
 * Mount every placement saved by \`clirevenue editor\` into its container.
 *
 * Call once from a plain <script type="module"> in the page. The container
 * is the placement's saved selector, defaulting to #clirevenue-ad.
 */
export async function mountPlacements() {
  const key = readPublishableKey();
  if (!key) {
    console.warn('[clirevenue] No publishable key found. Add a meta tag or set localStorage.');
    return;
  }

  const [{ init }, config] = await Promise.all([loadSdk(), loadConfig()]);
  const client = init(key, { baseUrl: readBaseUrl() });

  for (const integration of Object.values(config.integrations || {})) {
    for (const slot of Object.values(integration.slots || {})) {
      if (slot.enabled === false) continue;
      const selector = slot.container || '#clirevenue-ad';
      const host = document.querySelector(selector);
      if (!host) continue;
      client.render(integration.placementKey, selector, {
        size: slot.layout.size,
        position: slot.layout.position,
      });
    }
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => void mountPlacements());
} else {
  void mountPlacements();
}
`;

/**
 * The React adapter.
 *
 * `useId` generates ids containing colons, which are invalid in a CSS
 * selector unescaped — hence the `CSS.escape` on the lookup side. The ad box
 * itself is rendered by the SDK into the same element.
 */
const REACT_RENDER = `${GENERATED_HEADER}
import { useEffect, useId, useRef } from 'react';
import { renderPlacement } from '../lib/clirevenue.js';

const STYLE = { position: 'relative', minHeight: '1px' };

export function CLIRevenueAd({ placementKey, slotId, className }) {
  const id = useId();
  const ref = useRef(null);

  useEffect(() => {
    // useId() yields values like ":r0:" which CSS.escape() renders as
    // "\\\\:r0\\\\:", so the selector matches the element that actually exists.
    const selector = '#' + CSS.escape(id);
    // slotId is passed through so two components can share one placement key
    // and still sit where the editor put each of them. Without it every
    // instance would resolve to the integration's first slot and stack up in
    // the same corner.
    const handle = renderPlacement(placementKey, selector, slotId);
    return () => handle?.dispose?.();
  }, [placementKey, slotId]);

  return <div id={id} ref={ref} className={className ?? 'clirevenue-ad-slot'} style={STYLE} />;
}

export default CLIRevenueAd;
`;

const VUE_RENDER = `${GENERATED_HEADER}<script setup>
import { onBeforeUnmount, onMounted, ref } from 'vue';
import { renderPlacement } from '../lib/clirevenue.js';

const props = defineProps({
  placementKey: { type: String, required: true },
  // Optional: lets two components share one placement key and still use the
  // geometry the editor saved for each slot.
  slotId: { type: String, default: undefined },
});

const host = ref(null);
let handle = null;

onMounted(() => {
  // Vue's ref name becomes the element id, so the same escaped-selector
  // lookup the React adapter uses works here unchanged.
  handle = renderPlacement(props.placementKey, '#' + CSS.escape(host.value.id), props.slotId);
});

onBeforeUnmount(() => handle?.dispose?.());
</script>

<template>
  <div :id="host" class="clirevenue-ad-slot" />
</template>
`;

const SVELTE_RENDER = `${GENERATED_HEADER}<script>
  import { onMount, onDestroy } from 'svelte';
  import { renderPlacement } from '../lib/clirevenue.js';

  export let placementKey;
  // Optional: lets two components share one placement key and still use the
  // geometry the editor saved for each slot.
  export let slotId = undefined;

  let host;
  let handle = null;

  onMount(() => {
    handle = renderPlacement(placementKey, '#' + CSS.escape(host.id), slotId);
  });

  onDestroy(() => handle?.dispose?.());
</script>

<div bind:this={host} class="clirevenue-ad-slot" />
`;

/** Build the files for a stack. `sdkVersion` is interpolated for the CDN URL. */
export function adapterFiles(
  type: ProjectType,
  sdkVersion: string,
): Array<{ path: string; content: string }> {
  const entry = ADAPTER_FILES[type];
  if (!entry.entry) return [];

  const files: Array<{ path: string; content: string }> = [
    { path: entry.entry, content: type === 'static-html' ? STATIC_ENTRY.replace('__SDK_VERSION__', sdkVersion) : VITE_ENTRY },
  ];
  if (!entry.render) return files;

  const render: Partial<Record<ProjectType, string>> = {
    'vite-react': REACT_RENDER,
    'vite-vue': VUE_RENDER,
    'vite-svelte': SVELTE_RENDER,
  };
  const content = render[type];
  if (content) files.push({ path: entry.render, content });
  return files;
}
